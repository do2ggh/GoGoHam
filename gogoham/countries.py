def german_name(prefix: str, fallback: str = "") -> str:
    """Ländername für die Anzeige: auf Deutsch aus der eigenen Liste, in anderen Sprachen
    der (englische) Name aus der Länderdatei, der als ``fallback`` mitgegeben wird."""
    from .i18n import language
    if language() != "de" and fallback:
        return fallback
    entry = COUNTRIES.get((prefix or "").upper())
    return entry[0] if entry else (fallback or prefix)


def flag_code(prefix: str) -> str:
    entry = COUNTRIES.get((prefix or "").upper())
    return entry[1] if entry else ""


def all_flag_codes() -> list[str]:
    return sorted({code for _n, code in COUNTRIES.values() if code})
